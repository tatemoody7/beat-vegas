def grade_finals_landed(ctx: Ctx) -> Result:
    """The board's stale-results predicate (web/lib/boardHealth.ts getGradeHealth):
    a game THE MODEL RATED (a game_records row), kicked off > STALE_AFTER_HOURS
    ago, still without a final."""
    from sqlalchemy import exists

    from .db.models import Game, GameRecord

    cutoff = ctx.now - timedelta(hours=STALE_AFTER_HOURS)
    q = ctx.session.query(Game.id).filter(
        Game.season == ctx.season,
        Game.home_points.is_(None),
        Game.start_date < cutoff,
        exists().where(GameRecord.game_id == Game.id),
    )
    n = q.count()
    return Result(n == 0, f"{n} rated games kicked off >{STALE_AFTER_HOURS}h ago without a final")


