"""Health contracts: what each scheduled job must leave behind, checked by the
job itself as its last step and written where the board can read it.

Eleven of the fourteen failures of 2026-08/09 were runs that exited green and
produced nothing: a card build that died mid-sweep, a grading run that graded
zero picks, a scoring run whose inputs were 57 columns of NaN. GitHub's
failed-run email fires on none of those, and the gauges in `ops.py` say whether
the system CAN keep running, not whether the run that just finished DID what it
was for. A contract is that second question, written down as data:

    Contract  -- one per scheduled Neon-writing job (card, grade, sunday,
                 lines_watch): the workflow file, the artifacts the run must
                 leave, the env it is judged with, its checks, and the catalogue
                 of past failures each check would have caught.
    Check     -- ONE POSITIVE FACT about this run ("a cards row for this
                 season/week was written after the run started and carries this
                 slot"), with a severity: `failed` reddens the run (email),
                 `degraded` is board-only.
    evaluate  -- runs every check; the verdict is `failed` if any failed-severity
                 check misses, else `degraded` if any check misses, else `ok`.

scripts/health_check.py is the workflow step; it writes the verdict to the
`last_health_<job>` gauge (`ops.health_key`) with a <= 300-char note naming the
run, the trigger, the slot and every miss. web/lib/boardHealth.ts reads it into
the board banner and /api/health. docs/HEALTH.md carries the prose and a block
generated by `render_contracts()` (`python -m beatvegas.health --render-md
docs/HEALTH.md`); tests/test_docs_parity.py keeps the two equal.

Every timestamp here is NAIVE UTC, like every other timestamp in the database.
A check never raises: a check that cannot run is not a positive fact, so it is
reported as a miss with the exception's name in its detail.
"""

