def lines_watch_close_polled(ctx: Ctx) -> Result:
    st = ctx.status_files.get("close")
    if st is None:
        return Result(False, "no close status file")
    polled = int(st.get("events_polled") or 0)
    in_window = int(st.get("events_in_window") or 0)
    detail = f"polled={polled}/{in_window} complete={str(st.get('complete') is True).lower()}"
    if st.get("reason"):
        detail += f" reason={st.get('reason')}"
    return Result(polled > 0 or in_window == 0, detail)


def lines_watch_hr_rows_touched(ctx: Ctx) -> Result:
    """A close poll that reached an event wrote or re-saw a Hard Rock 1H row: an
    unchanged number writes no row and stamps last_seen_at (the close time)."""
    from .db.models import OddsSnapshot

    polled = _close_polled(ctx)
    if polled == 0:
        return Result(True, "n/a, no events polled")
    n = (
        ctx.session.query(OddsSnapshot.id)
        .filter(
            OddsSnapshot.book == HR_BOOK_KEY,
            OddsSnapshot.market == FIRST_HALF_MARKET,
            (OddsSnapshot.captured_at >= ctx.run_started_at)
            | (OddsSnapshot.last_seen_at >= ctx.run_started_at),
        )
        .count()
    )
    return Result(
        n > 0, f"{n} Hard Rock 1H rows captured or re-seen since {_iso(ctx.run_started_at)}"
    )


def lines_watch_close_gauge_written(ctx: Ctx) -> Result:
    polled = _close_polled(ctx)
    if polled == 0:
        return Result(True, "n/a, no events polled")
    _value, at = read_gauge(ctx.session, LAST_CLOSE_CAPTURE_AT)
    ok = at is not None and at >= ctx.run_started_at
    return Result(ok, f"{LAST_CLOSE_CAPTURE_AT} updated_at={_iso(at)}")


def lines_watch_info(ctx: Ctx) -> Dict[str, str]:
    st = ctx.status_files.get("close")
    out: Dict[str, str] = {}
    if st:
        out["polled"] = str(st.get("events_polled", "?"))
        out["credits"] = str(st.get("credits_spent", "?"))
    return out


