def _card_payload(ctx: Ctx) -> Optional[dict]:
    """The `cards` row this run wrote: (season, week), built after the run
    started, payload.slot == the resolved slot. Newest first; memoised."""
    if "card" in ctx.cache:
        return ctx.cache["card"]
    from .db.models import Card

    found: Optional[dict] = None
    if ctx.season is not None and ctx.week is not None:
        rows = (
            ctx.session.query(Card)
            .filter(
                Card.season == ctx.season,
                Card.week == ctx.week,
                Card.built_at >= ctx.run_started_at,
            )
            .order_by(Card.built_at.desc(), Card.id.desc())
            .all()
        )
        for row in rows:
            try:
                payload = json.loads(row.payload)
            except (TypeError, ValueError):
                continue
            if not isinstance(payload, dict):
                continue
            if ctx.slot is None or payload.get("slot") == ctx.slot:
                payload["_built_at"] = row.built_at
                found = payload
                break
    ctx.cache["card"] = found
    return found


def card_row_this_run(ctx: Ctx) -> Result:
    p = _card_payload(ctx)
    if p is None:
        return Result(
            False,
            f"no cards row for {ctx.season} w{ctx.week} slot={ctx.slot} "
            f"built since {_iso(ctx.run_started_at)}",
        )
    return Result(True, f"built_at={_iso(p.get('_built_at'))} items={len(p.get('items') or [])}")


def card_status_clean(ctx: Ctx) -> Result:
    p = _card_payload(ctx)
    if p is None:
        return Result(False, "no card row")
    expected = CARD_STATUS_BY_SLOT.get(ctx.slot or "")
    status = p.get("status")
    deg = p.get("degraded") or []
    names = ",".join(str(d.get("input", "?")) for d in deg if isinstance(d, dict))
    detail = f"status={status} (slot wants {expected}) degraded={len(deg)}"
    if names:
        detail += f" [{names}]"
    return Result(status == expected and not deg, detail)


def card_hr_priced_floor(ctx: Ctx) -> Result:
    p = _card_payload(ctx)
    if p is None:
        return Result(False, "no card row")
    n = sum(1 for it in p.get("items") or [] if it.get("hr_line") is not None)
    return Result(n >= HR_PRICED_FLOOR, f"{n} Hard Rock-priced items (floor {HR_PRICED_FLOOR})")


def card_paper_logged_iff_window(ctx: Ctx) -> Result:
    """A scheduled slot paper-logs every qualifying item inside its window
    (beatvegas/ci.py PAPER_WINDOW_HOURS; None = the rest of the week); `manual`
    logs nothing, because the first log of a game is the one that stays."""
    from .db.models import ManualPick
    from .picks import existing_pick

    if ctx.slot is None:
        return Result(False, "slot unknown")
    if ctx.slot not in SCHEDULED_SLOTS:
        n = (
            ctx.session.query(ManualPick.id)
            .filter(ManualPick.is_paper.is_(True), ManualPick.placed_at >= ctx.run_started_at)
            .count()
        )
        return Result(n == 0, f"{ctx.slot} build logged {n} paper picks (wants 0)")
    p = _card_payload(ctx)
    if p is None:
        return Result(False, "no card row")
    window = PAPER_WINDOW_HOURS.get(ctx.slot)
    expected: List[int] = []
    for it in p.get("items") or []:
        if not it.get("qualifies"):
            continue
        kick = _parse_kick(it.get("kick"))
        if window is not None and kick is not None:
            if kick - ctx.run_started_at > timedelta(hours=window):
                continue
        expected.append(int(it["game_id"]))
    missing = [
        gid for gid in expected if existing_pick(ctx.session, gid, "1H", is_paper=True) is None
    ]
    win = "rest of week" if window is None else f"{window:g}h"
    detail = f"{len(expected) - len(missing)}/{len(expected)} qualifying items in window ({win}) have a paper pick"
    if missing:
        detail += " missing " + ",".join(str(g) for g in missing[:6])
    return Result(not missing, detail)


def card_sweep_reached_slate(ctx: Ctx) -> Result:
    st = ctx.status_files.get("sweep")
    outcome = ctx.outcomes.get("sweep", "")
    if st is None:
        if outcome == "skipped":
            return Result(True, "sweep skipped, today's snapshot already on file")
        return Result(False, f"no sweep status file (sweep step outcome={outcome or 'unknown'})")
    polled = int(st.get("events_polled") or 0)
    in_window = int(st.get("events_in_window") or 0)
    complete = st.get("complete") is True
    detail = f"complete={str(complete).lower()} polled={polled}/{in_window} credits={st.get('credits_spent')}"
    if st.get("reason"):
        detail += f" reason={st.get('reason')}"
    return Result(complete and polled >= in_window, detail)


def card_info(ctx: Ctx) -> Dict[str, str]:
    p = _card_payload(ctx)
    out = {
        "sweep": ctx.outcomes.get("sweep", "?"),
        "preview": ctx.outcomes.get("preview", "?"),
    }
    if p is not None:
        items = p.get("items") or []
        out["early_season_held"] = str(
            sum(
                1
                for it in items
                if it.get("blocker") == "early_season" or it.get("gate_blocker") == "early_season"
            )
        )
        out["bets"] = str((p.get("counts") or {}).get("bet", "?"))
        # Games whose newest Hard Rock quote was an alternate line, shown at the
        # last main line and kept out of every gate (card.market_read).
        out["hr_alt_ignored"] = str(sum(1 for it in items if it.get("hr_alt_line") is not None))
    return out


