# --------------------------------------------------------------------------- #
# Evaluation
# --------------------------------------------------------------------------- #
def evaluate(contract: Contract, ctx: Ctx) -> Tuple[Verdict, List[Tuple[Check, Result]]]:
    """Run every check; a check that raises is a miss (not a positive fact)."""
    results: List[Tuple[Check, Result]] = []
    for check in contract.checks:
        try:
            res = check.fn(ctx)
        except Exception as e:  # noqa: BLE001 - the verdict must always be written
            res = Result(False, f"check raised {type(e).__name__}: {str(e)[:60]}")
        results.append((check, Result(bool(res.ok), _clean(res.detail))))
    if any(c.severity == "failed" and not r.ok for c, r in results):
        return "failed", results
    if any(not r.ok for _c, r in results):
        return "degraded", results
    return "ok", results


def verdict_note(job: str, ctx: Ctx, results: List[Tuple[Check, Result]]) -> str:
    """`run=<id> event=<name> slot=<slot> miss=<id>(<detail>);... info=k=v ...`,
    at most NOTE_MAX_CHARS. The board parses `run=` (link to the run) and
    `miss=` (the items); the rest is for a human reading the gauge row."""
    parts = [
        f"run={ctx.env.get('GITHUB_RUN_ID') or '-'}",
        f"event={ctx.env.get('GITHUB_EVENT_NAME') or '-'}",
    ]
    if ctx.slot:
        parts.append(f"slot={ctx.slot}")
    if ctx.market:
        parts.append(f"market={ctx.market}")
    misses = [(c.id, r.detail) for c, r in results if not r.ok]
    if misses:
        parts.append("miss=" + ";".join(f"{cid}({detail[:90]})" for cid, detail in misses))
    contract = CONTRACTS.get(job)
    info: Dict[str, str] = {}
    if contract is not None:
        try:
            info = contract.info(ctx)
        except Exception as e:  # noqa: BLE001 - info is a courtesy
            info = {"info_error": type(e).__name__}
    if info:
        parts.append("info=" + " ".join(f"{k}={_clean(str(v))}" for k, v in sorted(info.items())))
    note = " ".join(parts)
    if len(note) > NOTE_MAX_CHARS:
        note = note[: NOTE_MAX_CHARS - 3] + "..."
    return note


