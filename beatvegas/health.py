def _clean(detail: str) -> str:
    """A detail must not carry the two characters the note format uses."""
    return detail.replace(";", ",").replace("\n", " ")


def _iso(d: Optional[datetime]) -> str:
    return "none" if d is None else d.replace(microsecond=0).isoformat()


def _parse_kick(raw: Optional[str]) -> Optional[datetime]:
    """A card item's `kick` (ISO, trailing Z) as naive UTC -- the same parse
    scripts/build_card.py::log_paper_picks applies."""
    if not raw:
        return None
    try:
        return datetime.fromisoformat(str(raw).replace("Z", "+00:00")).replace(tzinfo=None)
    except ValueError:
        return None


def _fbs_slate(ctx: Ctx) -> List[Tuple[int, str, str]]:
    """(game_id, home, away) for the week's FBS-vs-FBS games -- the set the
    scorer reads (etl/fbs.py). A season the snapshot does not cover falls back
    to every game of the week, with the fallback named in the memo."""
    if "fbs_slate" in ctx.cache:
        return ctx.cache["fbs_slate"]
    from .db.models import Game
    from .etl.fbs import load_fbs_teams

    rows = (
        ctx.session.query(Game.id, Game.home_team, Game.away_team)
        .filter(Game.season == ctx.season, Game.week == ctx.week)
        .all()
    )
    members: Optional[Set[str]] = None
    try:
        members = load_fbs_teams().get(int(ctx.season)) if ctx.season is not None else None
    except (FileNotFoundError, ValueError):
        members = None
    if members is None:
        ctx.cache["fbs_note"] = "no FBS snapshot for the season, counting every game"
        slate = [(int(g), h, a) for g, h, a in rows]
    else:
        ctx.cache["fbs_note"] = ""
        slate = [(int(g), h, a) for g, h, a in rows if h in members and a in members]
    ctx.cache["fbs_slate"] = slate
    return slate


def _reference_cache_populated(ctx: Ctx) -> Result:
    """The CFBD reference files the feature frame joins. The PRIOR season's five
    are the priors every scored row needs and are what the check demands; the
    current season's files are reported, not required -- season_stats._cached_soft
    documents that a season still being played may have no full-year aggregate
    to fetch, so an absent current-season file can be correct."""
    if ctx.season is None:
        return Result(False, "season unknown")
    from .sources.season_stats import CACHE

    def _ok(name: str) -> bool:
        p = CACHE / name
        return p.exists() and p.stat().st_size > REFERENCE_CACHE_MIN_BYTES

    prior = ctx.season - 1
    missing = [f"{k}_{prior}.json" for k in REFERENCE_CACHE_KINDS if not _ok(f"{k}_{prior}.json")]
    current = sum(1 for k in REFERENCE_CACHE_KINDS if _ok(f"{k}_{ctx.season}.json"))
    n = len(REFERENCE_CACHE_KINDS)
    detail = f"{prior}: {n - len(missing)}/{n} files >{REFERENCE_CACHE_MIN_BYTES}B"
    if missing:
        detail += " missing " + ",".join(missing)
    detail += f", {ctx.season}: {current}/{n}"
    return Result(not missing, detail)


