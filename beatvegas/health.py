def sunday_pace_coverage(ctx: Ctx) -> Result:
    from .db.models import TeamTempo

    slate = _fbs_slate(ctx)
    teams: Set[str] = set()
    for _gid, h, a in slate:
        teams.add(h)
        teams.add(a)
    if not teams:
        return Result(False, "no FBS games on the slate")
    with_pace = {
        t
        for (t,) in ctx.session.query(TeamTempo.team)
        .filter(
            TeamTempo.season == ctx.season,
            TeamTempo.week == ctx.week,
            TeamTempo.seconds_per_play.isnot(None),
        )
        .distinct()
    }
    covered = len(teams & with_pace)
    share = covered / len(teams)
    detail = f"{covered}/{len(teams)} slate teams have a pace row ({share:.0%}, floor {PACE_COVERAGE_MIN:.0%})"
    if ctx.cache.get("fbs_note"):
        detail += f", {ctx.cache['fbs_note']}"
    return Result(share >= PACE_COVERAGE_MIN, detail)


def sunday_weather_coverage(ctx: Ctx) -> Result:
    from .db.models import Weather

    slate = _fbs_slate(ctx)
    if not slate:
        return Result(False, "no FBS games on the slate")
    ids = [gid for gid, _h, _a in slate]
    with_wx = ctx.session.query(Weather.game_id).filter(Weather.game_id.in_(ids)).count()
    share = with_wx / len(ids)
    detail = f"{with_wx}/{len(ids)} FBS games have a weather row ({share:.0%}, floor {WX_COVERAGE_MIN:.0%})"
    if ctx.cache.get("fbs_note"):
        detail += f", {ctx.cache['fbs_note']}"
    return Result(share >= WX_COVERAGE_MIN, detail)


