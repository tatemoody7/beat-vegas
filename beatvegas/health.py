CONTRACTS_BEGIN = "<!-- contracts:begin -->"
CONTRACTS_END = "<!-- contracts:end -->"


def render_contracts() -> str:
    """The generated block of docs/HEALTH.md. Deterministic: contracts in
    declaration order, one `### <job>` heading each (the anchor the board links
    to as docs/HEALTH.md#<job>)."""
    lines: List[str] = [
        CONTRACTS_BEGIN,
        "<!-- Generated by `python -m beatvegas.health --render-md docs/HEALTH.md`. Do not edit by hand. -->",
        "",
        "Parameters: " + ", ".join(f"`{k} = {v}`" for k, v in PARAMETERS.items()),
        "",
    ]
    for c in CONTRACTS.values():
        lines += [
            f"### {c.job}",
            "",
            f"- Workflow: `.github/workflows/{c.workflow}`",
            f"- Window: {c.window}",
            "- Artifacts: " + ", ".join(f"`{a}`" for a in c.artifacts),
            "- Inputs (env, beside `SKIPPED` and `RUN_STARTED_AT`): "
            + ", ".join(f"`{i}`" for i in c.inputs),
            "",
            "| Check | Severity | Positive fact |",
            "|---|---|---|",
        ]
        for ch in c.checks:
            lines.append(f"| `{ch.id}` | {ch.severity} | {ch.fact} |")
        lines += ["", "Failure modes on record:", ""]
        for fm in c.failure_modes:
            caught = ", ".join(f"`{i}`" for i in fm.caught_by) if fm.caught_by else "info only"
            lines.append(f"- **{fm.date}** -- {fm.what} Caught by: {caught}.")
        lines.append("")
    lines.append(CONTRACTS_END)
    return "\n".join(lines) + "\n"


def render_into(text: str) -> str:
    """Replace the block between the markers in a HEALTH.md body."""
    start = text.find(CONTRACTS_BEGIN)
    end = text.find(CONTRACTS_END)
    if start < 0 or end < 0 or end < start:
        raise ValueError("docs/HEALTH.md is missing the contracts:begin / contracts:end markers")
    end += len(CONTRACTS_END)
    # The block is rendered with its own trailing newline; keep whatever
    # followed the end marker in the file.
    tail = text[end:]
    if tail.startswith("\n"):
        tail = tail[1:]
    return text[:start] + render_contracts() + tail


def _main(argv: Optional[List[str]] = None) -> int:
    import argparse

    ap = argparse.ArgumentParser(description="Render the health contracts into docs/HEALTH.md.")
    ap.add_argument("--render-md", metavar="PATH", help="regenerate the contracts block in PATH")
    args = ap.parse_args(argv)
    if args.render_md:
        p = Path(args.render_md)
        p.write_text(render_into(p.read_text()))
        print(f"rendered {len(CONTRACTS)} contracts into {p}")
        return 0
