@dataclass
class Ctx:
    """Everything a check may read. `session` is an open SQLAlchemy session;
    `now` and `run_started_at` are naive UTC; `outcomes` maps a step name
    ("sweep", "preview", ...) to GitHub's step outcome ("success" / "failure" /
    "skipped" / "cancelled"); `status_files` holds the parsed JSON status files
    that exist ("sweep", "close"); `env` is the raw environment for details."""

    session: Any
    now: datetime
    job: str
    run_started_at: datetime
    season: Optional[int] = None
    week: Optional[int] = None
    slot: Optional[str] = None
    market: Optional[str] = None
    outcomes: Dict[str, str] = field(default_factory=dict)
    status_files: Dict[str, dict] = field(default_factory=dict)
    env: Mapping[str, str] = field(default_factory=dict)
    # Per-evaluation memo (the card row is read once for four checks).
    cache: Dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class Result:
    ok: bool
    detail: str


@dataclass(frozen=True)
class Check:
    id: str
    severity: Severity
    fact: str
    fn: Callable[[Ctx], Result]


@dataclass(frozen=True)
class FailureMode:
    date: str
    what: str
    caught_by: Tuple[str, ...]


def _no_info(ctx: Ctx) -> Dict[str, str]:
    return {}


@dataclass(frozen=True)
class Contract:
    job: str
    workflow: str
    window: str
    artifacts: Tuple[str, ...]
    inputs: Tuple[str, ...]
    checks: Tuple[Check, ...]
    failure_modes: Tuple[FailureMode, ...]
    # Facts worth carrying in the note that are never a miss (an early_season
    # hold is the gate working, not the job failing).
    info: Callable[[Ctx], Dict[str, str]] = _no_info


